/* Token generation. Reads config/, writes generated/:
 *   *.tokens.json  W3C DTCG: the ramps and qualitative set per theme, the scales
 *   tokens.css     the same values as custom properties, light and dark
 * config/ is the source of truth. Never edit generated/ by hand.
 *
 * Run: pnpm --filter @universal-analytics/tokens generate */
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { generateLeonardoTokens } from './leonardo.ts';
import { generateUtopiaTokens } from './utopia.ts';

type Tree = Record<string, unknown>;

/** Primitives are namespaced so they cannot collide with a host page's own. */
export const PREFIX = 'ua';

/** Flatten a DTCG tree to `--ua-a-b-c: value;` lines. Colours emit their hex, dimensions their clamp() or px, aliases a var(). */
export function toCustomProperties(tree: Tree, path: string[] = [PREFIX]): string[] {
  return Object.entries(tree).flatMap(([key, node]) => {
    if (key.startsWith('$') || node === null || typeof node !== 'object') return [];
    const here = [...path, key], value = (node as Tree).$value;
    if (value === undefined) return toCustomProperties(node as Tree, here);
    const v = value as string | { hex?: string; value?: number; unit?: string };
    const alias = typeof v === 'string' && /^\{(.+)\}$/.exec(v);
    const css = alias ? `var(--${PREFIX}-${alias[1]!.replace(/\./g, '-')})` : typeof v === 'string' ? v : v.hex ?? `${v.value}${v.unit}`;
    return [`--${here.join('-')}: ${css};`];
  });
}

/** The qualitative set for one theme, as aliases into that theme's ramps. */
export function qualitative(series: string[], step: number, ramps: Tree): Tree {
  const set: Tree = { $description: `Qualitative series, each at step ${step} of its ramp` };
  series.forEach((name, i) => {
    if (!(ramps[name] as Tree | undefined)?.[step]) {
      throw new Error(`qualitative.json: series ${i + 1} names "${name}" at step ${step}, which the ramps do not have. Use one of: ${Object.keys(ramps).filter((k) => !k.startsWith('$')).join(', ')}`);
    }
    set[i + 1] = { $value: `{color.${name}.${step}}` };
  });
  return set;
}

const block = (selector: string, lines: string[], indent = '') =>
  `${indent}${selector} {\n${lines.map((l) => `${indent}  ${l}`).join('\n')}\n${indent}}`;

/** The theming pattern the prototypes use: device preference, overridable either way by data-theme. */
export function toCSS(light: Tree, dark: Tree, fluid: Tree): string {
  const d = toCustomProperties(dark);
  return [
    '/* Generated by packages/tokens. Do not edit. */',
    block(':root', [...toCustomProperties(light), ...toCustomProperties(fluid)]),
    `@media (prefers-color-scheme: dark) {\n${block(':root:not([data-theme="light"])', d, '  ')}\n}`,
    block(':root[data-theme="dark"]', d),
  ].join('\n') + '\n';
}

if (import.meta.main) {
  const root = join(import.meta.dirname, '..'), out = join(root, 'generated');
  const leonardo = await generateLeonardoTokens(join(root, 'config/leonardo.json'));
  const utopia = await generateUtopiaTokens(join(root, 'config/utopia.json'));
  const q = JSON.parse(readFileSync(join(root, 'config/qualitative.json'), 'utf-8')) as { series: string[]; step: { light: number; dark: number } };
  for (const theme of ['light', 'dark'] as const) {
    const ramps = leonardo[theme].color as Tree;
    ramps.qualitative = qualitative(q.series, q.step[theme], ramps);
  }
  rmSync(out, { recursive: true, force: true });
  mkdirSync(out);
  const files: Record<string, Tree> = {
    'color.light': leonardo.light, 'color.dark': leonardo.dark,
    'scale.fluid': utopia.fluid, 'scale.min': utopia.min, 'scale.max': utopia.max,
  };
  for (const [name, tree] of Object.entries(files)) writeFileSync(join(out, `${name}.tokens.json`), JSON.stringify(tree, null, 2) + '\n');
  writeFileSync(join(out, 'tokens.css'), toCSS(leonardo.light, leonardo.dark, utopia.fluid));
  console.log(`Wrote ${Object.keys(files).length + 1} files to ${out}`);
}
